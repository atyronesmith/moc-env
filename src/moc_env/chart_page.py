"""Render the combined chart-and-values page for the ops-docs site.

The page reuses the rows and tables collected for the other chart views.  It
only controls document structure, Markdown escaping, and anchor links.
"""

from __future__ import annotations

import re
from typing import Iterable, Sequence
from urllib.parse import quote

from . import chart_reference
from .charts import (
    OVERRIDES_SCOPE_NOTE,
    UNDEPLOYED_NOTE,
    ChartCluster,
    ChartInventory,
    ChartInventoryError,
    _markdown_table,
    _scope_note,
    _summary_cell,
    _summary_tables,
)
from .repositories import OAC_APPS_REPOSITORY

_FRONT_MATTER = (
    "---",
    "title: oac-apps charts and values by cluster",
    "---",
)
_INTRO = (
    "This page shows which charts each hub and workload cluster receives from "
    "oac-apps and which values the repository sets for each chart. It is "
    "generated by `moc-env charts --view page` and should not be edited by "
    "hand. It describes what the repository declares, not live cluster state."
)
_VALUES_PARAGRAPH = (
    "For each chart, the value files named by the manifest that deploys it "
    "are compared with the chart's own `values.yaml`. The files are read in "
    "the order the manifest lists them, so later files win."
)
_CLUSTER_COLUMNS = ("Chart", "Key", "Status", "Default", "Value", "Set in")

_HEADING = re.compile(r"^(#{1,6}) +(.+?)\s*$")
_SAFE_URL_CHARACTERS = "!'()*-._~"


def heading_id(text: str) -> str:
    """Return the id markdown-it-anchor assigns to a heading's text."""

    slug = re.sub(r"\s+", "-", text.strip().lower())
    return quote(slug, safe=_SAFE_URL_CHARACTERS)


def _code_span(value: str) -> str:
    return chart_reference._code_span(value)


def _cell(value: str) -> str:
    return chart_reference._markdown_cell(value)


def _chart_cell(chart: str, rendered: set[str]) -> str:
    label = _cell(chart)
    if chart not in rendered:
        return label
    return f"[{label}](#{heading_id(chart)})"


def _file_cell(path: str, sha: str) -> str:
    if not path or path == "-":
        return _cell(_code_span(path or "-"))
    url = f"https://github.com/{OAC_APPS_REPOSITORY}/blob/{sha}/{path}"
    return _cell(f"[{_code_span(path)}]({url})")


def _source_line(sha: str) -> str:
    url = f"https://github.com/{OAC_APPS_REPOSITORY}/commit/{sha}"
    return f"Source: {OAC_APPS_REPOSITORY} at [{sha[:7]}]({url})."


def _summary_section(inventory: ChartInventory, rendered: set[str]) -> list[str]:
    lines = ["## Which clusters get which charts", ""]
    for table in _summary_tables(inventory):
        lines.append(f"### {table.name}")
        lines.append("")
        rows = [
            [
                (
                    ", ".join(
                        _chart_cell(name, rendered)
                        for name in value
                    )
                    if table.name == "Workload features" and index == 1
                    else _summary_cell(value)
                )
                for index, value in enumerate(row)
            ]
            for row in table.rows
        ]
        centered = {
            index
            for index in range(len(table.columns))
            if any(row[index] == "x" for row in table.rows)
        }
        lines.extend(
            _markdown_table(
                [str(column) for column in table.columns],
                rows,
                centered,
            )
        )
        lines.append("")
    return lines


def _cluster_rows(cluster: ChartCluster, rendered: set[str], sha: str) -> list[list[str]]:
    rows: list[list[str]] = []
    for entry in cluster.override_charts:
        chart = _chart_cell(str(entry["chart"]), rendered)
        for row in entry["overrides"]:
            default = (
                "-"
                if "default" not in row
                else _cell(
                    _code_span(
                        chart_reference.truncated_default(row["default"])
                    )
                )
            )
            rows.append(
                [
                    chart,
                    _cell(_code_span(str(row["key"]))),
                    _cell(str(row["status"])),
                    default,
                    _cell(
                        _code_span(
                            chart_reference.truncated_default(row["value"])
                        )
                    ),
                    _file_cell(str(row.get("source") or "-"), sha),
                ]
            )
    return rows


def _cluster_note_lines(cluster: ChartCluster) -> list[str]:
    no_overrides = [
        str(entry["chart"])
        for entry in cluster.override_charts
        if not entry["overrides"]
    ]
    restated = sum(int(entry["restated"]) for entry in cluster.override_charts)
    not_compared = "; ".join(
        f"{item['chart']} ({item['reason']})"
        for item in cluster.not_compared
    )
    return [
        "Charts with no overrides: "
        + (", ".join(no_overrides) or "(none)"),
        "",
        f"Restated values not shown: {restated}",
        "",
        "Not compared: " + (not_compared or "(none)"),
    ]


def _values_section(inventory: ChartInventory, rendered: set[str]) -> list[str]:
    lines = [
        "## Values set for each cluster",
        "",
        _VALUES_PARAGRAPH,
        "",
    ]
    for cluster in inventory.clusters:
        lines.extend([f"### {cluster.name} ({cluster.kind})", ""])
        if cluster.error:
            lines.extend([f"Error: {cluster.error}", ""])
        else:
            lines.extend(
                _markdown_table(
                    list(_CLUSTER_COLUMNS),
                    _cluster_rows(cluster, rendered, inventory.sha),
                    escape_cells=False,
                )
            )
            lines.append("")
        lines.extend(_cluster_note_lines(cluster))
        lines.append("")
    return lines


def _reference_section(inventory: ChartInventory) -> list[str]:
    reference = inventory.reference
    if reference is None:
        raise ChartInventoryError(
            "the chart reference was not collected for this inventory"
        )
    lines = [
        "## Chart values reference",
        "",
        chart_reference._CHART_REFERENCE_PARAGRAPH,
        "",
    ]
    lines.extend(f"- {item}" for item in chart_reference._CHART_REFERENCE_ITEMS)
    lines.extend(["", chart_reference._CHART_REFERENCE_NOTE, ""])
    lines.extend(
        chart_reference.chart_entries_markdown(
            reference.charts, escape_addresses=True
        )
    )
    return lines


def _coverage_section(inventory: ChartInventory) -> list[str]:
    lines = ["## What this page does not cover", "", OVERRIDES_SCOPE_NOTE, ""]
    scope_note = _scope_note(inventory) if inventory.hidden_clusters else None
    if scope_note:
        lines.extend([scope_note, ""])
    undeployed = len(inventory.undeployed_charts)
    library = len(inventory.library_charts)
    lines.extend(
        [
            UNDEPLOYED_NOTE,
            "",
            f"{undeployed} undeployed and {library} library charts are not "
            "shown.",
        ]
    )
    return lines


def _clean_lines(lines: Iterable[str]) -> list[str]:
    cleaned: list[str] = []
    for line in lines:
        line = line.rstrip()
        if not line and (not cleaned or not cleaned[-1]):
            continue
        cleaned.append(line)
    while cleaned and not cleaned[-1]:
        cleaned.pop()
    return cleaned


def _check_headings(lines: Sequence[str], from_matter: int) -> None:
    seen: set[str] = set()
    in_fence = False
    for line in lines[from_matter:]:
        if line.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        match = _HEADING.match(line)
        if match is None:
            continue
        level = len(match.group(1))
        text = match.group(2).strip()
        if level == 1 or level > 3:
            raise ChartInventoryError(
                f"page heading {text!r} must use ## or ###"
            )
        if text in seen:
            raise ChartInventoryError(
                f"page heading {text!r} is not unique"
            )
        seen.add(text)


def render_chart_page(inventory: ChartInventory) -> str:
    """Render the single-page chart and values document."""

    reference = inventory.reference
    if reference is None:
        raise ChartInventoryError(
            "the chart reference was not collected for this inventory"
        )
    rendered = {entry.name for entry in reference.charts}
    body: list[str] = [
        _INTRO,
        "",
        _source_line(inventory.sha),
        "",
        *_summary_section(inventory, rendered),
        *_values_section(inventory, rendered),
        *_reference_section(inventory),
        "",
        *_coverage_section(inventory),
    ]
    body = _clean_lines(body)
    if any("{{" in line or "{%" in line for line in body):
        body = ["{% raw %}", "", *body, "", "{% endraw %}"]
    lines = [*_FRONT_MATTER, "", *body]
    _check_headings(lines, len(_FRONT_MATTER))
    return "\n".join(lines) + "\n"
